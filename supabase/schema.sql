create or replace function public.place_demo_order(p_symbol text, p_side text, p_quantity numeric)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_account demo_accounts%rowtype;
  v_holding demo_holdings%rowtype;
  v_stock stocks%rowtype;
  v_total numeric(14,2);
  v_new_average numeric(12,2);
  v_order_id uuid;
begin
  if p_side not in ('buy', 'sell') then raise exception 'Side must be buy or sell'; end if;
  if p_quantity is null or p_quantity <= 0 then raise exception 'Quantity must be greater than zero'; end if;

  select * into v_stock from stocks where symbol = upper(p_symbol) for update;
  if not found then raise exception 'Stock % was not found', p_symbol; end if;
  select * into v_account from demo_accounts where id = 'demo-user' for update;
  select * into v_holding from demo_holdings where account_id = 'demo-user' and symbol = v_stock.symbol for update;
  v_total := round(v_stock.price * p_quantity, 2);

  if p_side = 'buy' then
    if v_account.cash < v_total then raise exception 'Insufficient cash'; end if;
    v_new_average := round(((coalesce(v_holding.quantity, 0) * coalesce(v_holding.average_cost, 0)) + v_total) / (coalesce(v_holding.quantity, 0) + p_quantity), 2);
    update demo_accounts set cash = cash - v_total, updated_at = now() where id = 'demo-user';
    insert into demo_holdings(account_id, symbol, quantity, average_cost) values ('demo-user', v_stock.symbol, p_quantity, v_new_average)
    on conflict (account_id, symbol) do update set quantity = demo_holdings.quantity + excluded.quantity, average_cost = excluded.average_cost, updated_at = now();
  else
    if coalesce(v_holding.quantity, 0) < p_quantity then raise exception 'Insufficient shares'; end if;
    update demo_accounts set cash = cash + v_total, updated_at = now() where id = 'demo-user';
    update demo_holdings set quantity = quantity - p_quantity, updated_at = now() where account_id = 'demo-user' and symbol = v_stock.symbol;
  end if;

  insert into demo_orders(account_id, symbol, side, quantity, price, total) values ('demo-user', v_stock.symbol, p_side, p_quantity, v_stock.price, v_total) returning id into v_order_id;
  return json_build_object('order_id', v_order_id, 'symbol', v_stock.symbol, 'side', p_side, 'quantity', p_quantity, 'price', v_stock.price, 'total', v_total);
end;
$$;
