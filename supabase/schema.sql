-- Seed one year of daily simulated history for each symbol. Existing dates are skipped.
insert into public.stock_price_history (symbol, price, recorded_at, granularity, sample_date)
select
  s.symbol,
  greatest(0.01, round((s.price * (1 + sin(g.day_offset * 0.37 + length(s.symbol)) * 0.08 + (random() - 0.5) * 0.03))::numeric, 2)),
  (current_date - g.day_offset)::timestamptz + interval '12 hours',
  'day',
  current_date - g.day_offset
from public.stocks s
cross join generate_series(0, 364) as g(day_offset)
where not exists (
  select 1 from public.stock_price_history h
  where h.symbol = s.symbol
    and h.granularity = 'day'
    and h.sample_date = current_date - g.day_offset
);

