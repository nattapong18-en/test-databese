create table if not exists public.stocks (
  symbol text primary key,
  name text not null,
  exchange text not null default 'NASDAQ',
  price numeric(12,2) not null check (price >= 0),
  open numeric(12,2) not null check (open >= 0),
  high numeric(12,2) not null check (high >= 0),
  low numeric(12,2) not null check (low >= 0),
  change numeric(8,2) not null default 0,
  volatility numeric(6,3) not null default 0.550 check (volatility >= 0 and volatility <= 20),
  updated_at timestamptz not null default now()
);

alter table public.stocks add column if not exists volatility numeric(6,3) not null default 0.550;
alter table public.stocks add column if not exists manual_override_until timestamptz;
alter table public.stocks replica identity full;

create table if not exists public.stock_price_history (
  id bigint generated by default as identity primary key,
  symbol text not null references public.stocks(symbol) on delete cascade,
  price numeric(12,2) not null check (price >= 0),
  recorded_at timestamptz not null default now(),
  granularity text not null default 'tick' check (granularity in ('tick', 'day')),
  sample_date date not null default current_date
);

create index if not exists stock_price_history_symbol_time_idx
  on public.stock_price_history(symbol, recorded_at desc);
create index if not exists stock_price_history_symbol_granularity_time_idx
  on public.stock_price_history(symbol, granularity, recorded_at desc);

create table if not exists public.demo_accounts (
  id text primary key,
  cash numeric(14,2) not null check (cash >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.demo_holdings (
  account_id text not null references public.demo_accounts(id) on delete cascade,
  symbol text not null references public.stocks(symbol) on delete cascade,
  quantity numeric(14,4) not null default 0 check (quantity >= 0),
  average_cost numeric(12,2) not null default 0 check (average_cost >= 0),
  updated_at timestamptz not null default now(),
  primary key (account_id, symbol)
);

create table if not exists public.demo_orders (
  id uuid primary key default gen_random_uuid(),
  account_id text not null references public.demo_accounts(id) on delete cascade,
  symbol text not null references public.stocks(symbol),
  side text not null check (side in ('buy', 'sell')),
  quantity numeric(14,4) not null check (quantity > 0),
  price numeric(12,2) not null check (price >= 0),
  total numeric(14,2) not null check (total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists demo_orders_account_time_idx
  on public.demo_orders(account_id, created_at desc);

